# ===== 第一层：关键词命中 =====
def keyword_hit(text: str) -> bool:
    if not text:
        return False
    return any(kw in text for kw in INGREDIENT_KEYWORDS)


# ===== 第二层：LLM 兜底 =====
async def llm_judge_ingredient(images_b64: list[str], text: str) -> tuple[bool, list[str]]:
    """用 LLM 判断是否有食材/菜品，并返回识别出的主要食材名列表。

    失败视为非食材（保守）。
    """
    user_text = (text or "").strip() or "（用户没有输入文字）"
    raw = await chat_vision(
        system=INTENT_JUDGE_PROMPT,
        user=user_text,
        images_b64=images_b64,
        max_tokens=256,
    )
    raw = raw.strip()
    logger.debug(f"LLM 意图识别输出: {raw!r}")

    if not raw.upper().startswith("YES"):
        return False, []

    # 提取 YES 后的食材列表
    payload = raw[3:].strip().strip("：:").strip()
    ingredients = [s.strip() for s in payload.split(",") if s.strip()]
    return True, ingredients


# ===== 主入口 =====
async def check_intent(images_b64: list[str], text: str) -> tuple[bool, list[str]]:
    """检查用户输入是否包含食材/菜品。

    返回 (是否相关, 识别出的食材列表)
    - 关键词命中：直接通过，食材列表从关键词匹配出
    - LLM 兜底：模型判断 + 返回食材列表
    - 都没有：返回 (False, [])
    """
    # 第一层：关键词
    if keyword_hit(text):
        # 提取命中的关键词
        matched = [kw for kw in INGREDIENT_KEYWORDS if kw in (text or "")]
        # 顺便把文字里所有命中的关键词当作"识别的食材"
        return True, matched[:10]

    # 第二层：必须有图片才走 LLM
    if not images_b64:
        return False, []

    return await llm_judge_ingredient(images_b64, text)
